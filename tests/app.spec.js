 await expect(page.locator('main')).toContainText('Test medicine 5 mg')
 await expect(page.locator('main')).toContainText('Symptoms interrupted my sleep.')
 await expect(page.locator('.care-card.urgent').first()).toBeVisible()
 await expect(page.locator('main')).not.toContainText('Cetirizine')
 const download=page.waitForEvent('download');await page.getByRole('button',{name:'Download GP report (PDF)'}).click()
 expect((await download).suggestedFilename()).toMatch(/herhealth-gp-summary-.*\.pdf/)
 const textDownload=page.waitForEvent('download');await page.getByRole('button',{name:'Download text copy'}).click()
 expect((await textDownload).suggestedFilename()).toBe('herhealth-summary.txt')
 await page.getByRole('link',{name:'Edit my answers'}).click()
 await page.getByRole('textbox',{name:/Anything you would/}).fill('Updated answers need a new report.')
 await page.evaluate(()=>location.hash='summary')
 await expect(page.getByRole('heading',{name:'Your answers have changed'})).toBeVisible()
